'use strict';

/**
 * Bundles the shared engine (src/*.js) into one browser script, `core.js`, so the
 * whole app can also run with zero install on GitHub Pages (offline rules + Urimai engine).
 *
 *   node tools/build-core.js <outDir>   -> writes <outDir>/core.js
 */

const fs = require('node:fs');
const path = require('node:path');

const SRC = path.join(__dirname, '..', 'src');
const MODULES = [
  'languages',
  'lru',
  'rules',
  'extract',
  'upiCheck',
  'content',
  'urimai',
  'radarData',
  'autopilot',
  'engine',
];

function buildCore() {
  const defs = MODULES.map((name) => {
    const code = fs.readFileSync(path.join(SRC, `${name}.js`), 'utf8');
    return `defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${code}\n};`;
  }).join('\n');

  return `/* Chat_Safe x Urimai core — generated by tools/build-core.js from src/. Do not edit by hand. */
(function () {
  'use strict';
  var defs = {};
  var cache = {};
  function require(name) {
    var key = name.replace(/^\\.\\//, '').replace(/\\.js$/, '');
    if (!defs[key]) throw new Error('core: unknown module ' + name);
    if (!cache[key]) {
      var module = { exports: {} };
      cache[key] = module;
      defs[key](module, module.exports, require);
    }
    return cache[key].exports;
  }
${defs}
  window.ChatSafeCore = require('engine');
})();
`;
}

if (require.main === module) {
  const outDir = process.argv[2] || path.join(__dirname, '..', 'public');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'core.js'), buildCore());
  console.log(`core.js written to ${outDir}`);
}

module.exports = { buildCore, MODULES };
